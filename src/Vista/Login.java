            /**
            * Valida los datos ingresados por el usuario.
            * 
            * Si el correo y la contraseña no están vacíos, consulta la base de datos.
            * Si las credenciales son correctas, abre la ventana principal del sistema.
            * Si son incorrectas, muestra un mensaje de error.
            */
            public void validar(){
             String correo = txtCorreo.getText().trim();
             String pass = String.valueOf(txtPass.getPassword()).trim();

             if(!correo.isEmpty() && !pass.isEmpty()){
                 lg = login.log(correo, pass);

                 if(lg.getCorreo() != null && lg.getPass() != null){
                     Sistema sis = new Sistema(lg);
                     sis.setVisible(true);
                     this.dispose();
                 } else {
                     JOptionPane.showMessageDialog(null, "Correo o contraseña incorrecta");
                 }

             } else {
                 JOptionPane.showMessageDialog(null, "Ingrese correo y contraseña");
             }
         }

